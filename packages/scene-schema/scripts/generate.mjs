function generateValidator(schemas, rootId, exportName) {
	const ajv = new Ajv2020({
		allErrors: true,
		code: {
			esm: true,
			source: true,
		},
		strict: true,
	});
	for (const { schema } of schemas) {
		ajv.addSchema(schema);
	}
	ajv.getSchema(rootId);
	const standalone = standaloneCode(ajv, { [exportName]: rootId }).replace(
		/const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/,
		`const $1 = (value) => { let length = 0; for (const _character of value) length++; return length; };`,
	);
	if (standalone.includes('require("ajv/')) {
		throw new Error('Generated validator still depends on the Ajv runtime.');
	}
	return `// @ts-nocheck -- generated standalone validator\n${standalone}\n`;
}

const schemas = await readSchemas();
await mkdir(generatedDirectory, { recursive: true });
await writeIfChanged(join(generatedDirectory, 'schemas.ts'), buildSchemaModule(schemas));
await writeIfChanged(join(generatedDirectory, 'chart-scene.ts'), await generateTypes());
await writeIfChanged(
	join(generatedDirectory, 'time-series-scene.ts'),
	await generateTimeSeriesTypes(),
);
await writeIfChanged(
	join(generatedDirectory, 'validate-chart-scene.ts'),
	generateValidator(
		schemas,
		'https://baron.dev/kline-scene/chart-scene.schema.json',
		'validateChartScene',
	),
);
await writeIfChanged(
	join(generatedDirectory, 'validate-time-series-scene.ts'),
	generateValidator(
		schemas,
		'https://baron.dev/kline-scene/time-series-scene.schema.json',
		'validateTimeSeriesScene',
	),
);
